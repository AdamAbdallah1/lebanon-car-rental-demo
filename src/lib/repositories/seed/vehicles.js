const STAMP = "2026-10-08T00:00:00.000Z";

const base = {
  status: "active",
  currency: "USD",
  weeklyDiscountPct: 10,
  weeklyMinDays: 7,
  monthlyDiscountPct: 20,
  monthlyMinDays: 28,
  createdAt: STAMP,
  updatedAt: STAMP,
};

function vehicle(config) {
  return {
    ...base,
    ...config,
    pricing: {
      currency: config.currency ?? base.currency,
      daily: config.dailyRate,
      weeklyDiscountPct: config.weeklyDiscountPct ?? base.weeklyDiscountPct,
      weeklyMinDays: config.weeklyMinDays ?? base.weeklyMinDays,
      monthlyDiscountPct: config.monthlyDiscountPct ?? base.monthlyDiscountPct,
      monthlyMinDays: config.monthlyMinDays ?? base.monthlyMinDays,
    },
    mileage: {
      includedPerDayKm: config.includedKm,
      overagePerKm: config.overagePerKm ?? 0.25,
    },
    media: config.shots.map((id, index) =>
      media(id, {
        alt: {
          en: `${config.name.en} — photograph ${index + 1}`,
          ar: `${config.name.ar ?? config.name.en} — صورة ${index + 1}`,
        },
      }),
    ),
  };
}

